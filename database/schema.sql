BEFORE UPDATE ON PRODUCTS FOR EACH ROW
BEGIN :NEW.UPDATED_AT := SYSDATE; END;
/

CREATE OR REPLACE TRIGGER TRG_WAREHOUSES_UPDATED_AT
BEFORE UPDATE ON WAREHOUSES FOR EACH ROW
BEGIN :NEW.UPDATED_AT := SYSDATE; END;
/

CREATE OR REPLACE TRIGGER TRG_SUPPLIERS_UPDATED_AT
BEFORE UPDATE ON SUPPLIERS FOR EACH ROW
BEGIN :NEW.UPDATED_AT := SYSDATE; END;
/

