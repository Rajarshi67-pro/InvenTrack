CREATE OR REPLACE TRIGGER TRG_LOW_STOCK
AFTER UPDATE OF STOCK_QTY
ON PRODUCTS
FOR EACH ROW
WHEN (NEW.STOCK_QTY < NEW.REORDER_LEVEL)

BEGIN

INSERT INTO INVENTORY_ALERTS
(
ALERT_ID,
PRODUCT_ID,
ALERT_TYPE,
MESSAGE,
ALERT_DATE
)

VALUES
(
INVENTORY_ALERT_SEQ.NEXTVAL,
:NEW.PRODUCT_ID,
'LOW STOCK',
'Product stock below reorder level',
SYSDATE
);

END;
